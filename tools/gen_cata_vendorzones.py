#!/usr/bin/env python3
"""Generate internal/db/catazones_gen.go — vendor-hub zone names for
Cataclysm vendor sources.

The wowsims zone list carries dungeon/raid zones only; vendor sources
point at hub zones (capitals, daily hubs like the Molten Front) whose
ids would otherwise render location-less.

Bulk upstream (no scraping): assets/db_inputs/wowhead_gearplannerdb.txt
vendored in wowsims/cata at the pinned commit — which zone ids vendor
sources reference. The names are curated below; the generator emits
only referenced ids and warns about uncurated ones on stderr.

(An earlier revision also emitted vendor GOLD prices from ItemSparse
BuyPrice — removed: the generic 4.4 "Weapons Vendor" catch-up NPCs
behind most of those listings turned out to be phantom wowhead data
(verified absent in-game on Whitemane), and legitimate vendor upgrades
are priced in currencies the justice/valor tables already cover.)

Usage:
    python3 tools/gen_cata_vendorzones.py > internal/db/catazones_gen.go
    gofmt -w internal/db/catazones_gen.go

Env:
    WOWSIMS_CATA_DB   path to a local db.json (default: fetch pinned URL)
    WOWHEAD_GPDB      path to a local wowhead_gearplannerdb.txt (default: fetch)
"""

import json
import os
import re
import sys
import urllib.request

PINNED = "70d87383a9b92f30fb9e370c4676d3ce33b6e6b6"
DB_URL = f"https://raw.githubusercontent.com/wowsims/cata/{PINNED}/assets/database/db.json"
GPDB_URL = f"https://raw.githubusercontent.com/wowsims/cata/{PINNED}/assets/db_inputs/wowhead_gearplannerdb.txt"

# Vendor-hub AreaTable ids the wowsims zone list does not carry.
ZONE_NAMES = {
    616: "Mount Hyjal",
    1519: "Stormwind City",
    1637: "Orgrimmar",
    4080: "Isle of Quel'Danas",
    4395: "Dalaran",
    4922: "Twilight Highlands",
    5034: "Uldum",
    5042: "Deepholm",
    5144: "Shimmering Expanse",
    5389: "Tol Barad Peninsula",
    5733: "Molten Front",
}


def fetch(url, env):
    path = os.environ.get(env)
    if path:
        return open(path, encoding="utf-8").read()
    print(f"fetching {url}", file=sys.stderr)
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def load_gearplanner(raw):
    """WH.setPageData("wow.gearPlanner.cata.item", {...}) statements;
    each payload is JSON with trailing commas (same parse as
    gen_cata_sources.py)."""
    out = {}
    for m in re.finditer(r'WH\.setPageData\("wow\.gearPlanner\.cata\.item", ', raw):
        s = m.end()
        depth = 0
        for j in range(s, len(raw)):
            if raw[j] == "{":
                depth += 1
            elif raw[j] == "}":
                depth -= 1
                if depth == 0:
                    out.update(json.loads(re.sub(r",\s*}", "}", raw[s : j + 1])))
                    break
    return {int(k): v for k, v in out.items()}


def main():
    db = json.loads(fetch(DB_URL, "WOWSIMS_CATA_DB"))
    pool = {it["id"] for it in db["items"]}
    known_zones = {z["id"] for z in db.get("zones", [])}
    gp = load_gearplanner(fetch(GPDB_URL, "WOWHEAD_GPDB"))

    zone_ids = set()
    for iid, e in gp.items():
        if iid not in pool or 5 not in (e.get("source") or []):
            continue
        for sm in e.get("sourcemore") or []:
            if sm.get("z"):
                zone_ids.add(sm["z"])
    missing = sorted(z for z in zone_ids if z not in known_zones)
    for z in missing:
        if z not in ZONE_NAMES:
            print(f"warning: vendor zone {z} has no curated name", file=sys.stderr)
    print(f"vendor zones missing upstream: {len(missing)}", file=sys.stderr)

    w = sys.stdout.write
    w("// Code generated by tools/gen_cata_vendorzones.py from the wowhead\n")
    w(f"// dump vendored in wowsims/cata @ {PINNED[:8]}; DO NOT EDIT.\n\n")
    w("package db\n\n")
    w("// cataVendorZones names vendor-hub zones the upstream zone list\n")
    w("// lacks; merged into Zones at load (existing names win).\n")
    w("var cataVendorZones = map[int]string{\n")
    for z in missing:
        if z in ZONE_NAMES:
            w(f'\t{z}: "{ZONE_NAMES[z]}",\n')
    w("}\n")


if __name__ == "__main__":
    main()
