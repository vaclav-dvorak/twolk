#!/usr/bin/env python3
"""Generate internal/db/gemenchants_gen.go — gem enchantment ID → gem item.

The armory's item links encode socketed gems as SpellItemEnchantment IDs
("gems=3519:0:0"), while our database keys gems by item ID. The mapping
lives in a client DBC we don't ship; each gem's wotlkdb page links its
enchantment, so this generator resolves it once for every gem in our
database (~366 pages, cached, throttled — a bounded one-time scrape after
bulk sources came up empty: wowhead's planner data and aowow listings
carry no enchantment IDs).

Usage:
    python3 tools/gen_gemenchants.py > internal/db/gemenchants_gen.go

Env:
    WOWSIMS_DB        path to a local db.json (default: fetch pinned URL)
    GEN_SOURCES_CACHE directory caching item html pages across runs
"""

import json
import os
import re
import sys
import time
import urllib.request

PINNED = "02e0d9fba5acb5c0a3d9248cb82285641540a1a9"
DB_URL = f"https://raw.githubusercontent.com/wowsims/wotlk/{PINNED}/assets/database/db.json"


def load_db():
    path = os.environ.get("WOWSIMS_DB")
    if path:
        with open(path) as f:
            return json.load(f)
    with urllib.request.urlopen(DB_URL, timeout=60) as r:
        return json.load(r)


def fetch_item(iid):
    cache = os.environ.get("GEN_SOURCES_CACHE")
    fp = f"{cache}/item{iid}.html" if cache else None
    if fp and os.path.exists(fp):
        with open(fp) as f:
            return f.read()
    req = urllib.request.Request(
        f"https://wotlkdb.com/?item={iid}",
        headers={"User-Agent": "twolk-gen-gemenchants/1.0"},
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        html = r.read().decode("utf-8", "replace")
    if fp:
        with open(fp, "w") as f:
            f.write(html)
    time.sleep(0.4)
    return html


def main():
    gems = load_db()["gems"]
    print(f"{len(gems)} gems to resolve", file=sys.stderr)
    mapping = {}
    misses = []
    for n, g in enumerate(sorted(gems, key=lambda g: g["id"]), 1):
        try:
            html = fetch_item(g["id"])
        except Exception as e:  # noqa: BLE001
            print(f"  {g['id']} {g['name']}: fetch failed: {e}", file=sys.stderr)
            misses.append(g["id"])
            continue
        m = re.search(r"enchantment=(\d+)", html)
        if m:
            mapping[int(m.group(1))] = g["id"]
        else:
            misses.append(g["id"])
        if n % 50 == 0:
            print(f"  {n}/{len(gems)}", file=sys.stderr)

    print("// Code generated by tools/gen_gemenchants.py from wotlkdb.com")
    print("// (3.3.5a database); DO NOT EDIT.")
    print("//")
    print("// Maps gem SpellItemEnchantment IDs (as armory item links encode")
    print("// socketed gems) to gem item IDs.")
    print()
    print("package db")
    print()
    print("var gemEnchantToItem = map[int]int{")
    for ench in sorted(mapping):
        print(f"\t{ench}: {mapping[ench]},")
    print("}")
    print(f"{len(mapping)} mapped, {len(misses)} misses: {misses}", file=sys.stderr)


if __name__ == "__main__":
    main()
