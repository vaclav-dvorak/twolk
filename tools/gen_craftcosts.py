#!/usr/bin/env python3
"""Generate internal/db/craftcosts_gen.go — crafting reagents for every
pool-relevant crafted item (ilvl >= 130), scraped from wotlkdb.com
(original 3.3.5a database) spell pages via the recipes' spell IDs the
upstream data already carries. Items whose recipe page yields no
reagents are logged and omitted (cost display falls back to the plain
profession line).

Usage:
    python3 tools/gen_craftcosts.py > internal/db/craftcosts_gen.go

Env:
    WOWSIMS_DB        path to a local db.json (default: fetch pinned URL)
    GEN_SOURCES_CACHE directory caching html pages across runs
"""

import json
import os
import re
import sys
import time
import urllib.request

PINNED = "02e0d9fba5acb5c0a3d9248cb82285641540a1a9"
DB_URL = f"https://raw.githubusercontent.com/wowsims/wotlk/{PINNED}/assets/database/db.json"

MIN_ILVL = 130  # keep in sync with the TUI's minUsefulILvl


def load_db():
    path = os.environ.get("WOWSIMS_DB")
    if path:
        with open(path) as f:
            return json.load(f)
    with urllib.request.urlopen(DB_URL, timeout=60) as r:
        return json.load(r)


def fetch(url, key):
    cache = os.environ.get("GEN_SOURCES_CACHE")
    fp = f"{cache}/{key}.html" if cache else None
    if fp and os.path.exists(fp):
        with open(fp) as f:
            return f.read()
    req = urllib.request.Request(url, headers={"User-Agent": "twolk-gen-craftcosts/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        html = r.read().decode("utf-8", "replace")
    if fp:
        with open(fp, "w") as f:
            f.write(html)
    time.sleep(0.4)
    return html


# 3.3.5 currency.dbc ids for the five badge currencies → Go const names
EMBLEM_CURRENCIES = {
    101: "EmblemHeroism",
    102: "EmblemValor",
    221: "EmblemConquest",
    301: "EmblemTriumph",
    341: "EmblemFrost",
}


def emblem_cost(html):
    """Cheapest single-currency emblem price in the sold-by rows."""
    best = None
    for grp in re.findall(r'"cost":\[\d+,\[((?:\[\d+,\d+\],?)+)\]\]', html):
        pairs = re.findall(r"\[(\d+),(\d+)\]", grp)
        if len(pairs) != 1:  # mixed-cost vendors: not a plain badge price
            continue
        cur, cnt = int(pairs[0][0]), int(pairs[0][1])
        if cur in EMBLEM_CURRENCIES and (best is None or cnt < best[1]):
            best = (cur, cnt)
    return best


def reagents(html):
    """Parse the Reagents block of a wotlkdb spell page tooltip."""
    # the tooltip lives inside a JS string: unescape \/ first
    txt = html.replace("\\/", "/")
    m = re.search(r'Reagents:.*?<div class=\\?"indent q1\\?">(.*?)</div>', txt, re.S)
    if not m:
        return []
    out = []
    for iid, name, count in re.findall(
        r'\?item=(\d+)\\?">([^<]+)</a>(?:\s*\((\d+)\))?', m.group(1)
    ):
        out.append((int(iid), name, int(count) if count else 1))
    return out


def main():
    db = load_db()
    todo = []  # (itemID, [spellIDs])
    for it in db["items"]:
        if it.get("ilvl", 0) < MIN_ILVL:
            continue
        spells = [
            s["crafted"]["spellId"]
            for s in it.get("sources") or []
            if s.get("crafted") and s["crafted"].get("spellId")
        ]
        if spells:
            todo.append((it["id"], spells))
    todo.sort()
    print(f"{len(todo)} crafted items to resolve", file=sys.stderr)

    entries = {}
    misses = []
    for n, (iid, spells) in enumerate(todo, 1):
        got = []
        for sid in spells:  # faction-mirrored recipes: first that parses wins
            try:
                got = reagents(fetch(f"https://wotlkdb.com/?spell={sid}", f"spell{sid}"))
            except Exception as e:  # noqa: BLE001
                print(f"  {iid}/spell {sid}: fetch failed: {e}", file=sys.stderr)
            if got:
                break
        if got:
            entries[iid] = got
        else:
            misses.append(iid)
        if n % 50 == 0:
            print(f"  {n}/{len(todo)}", file=sys.stderr)

    # second pass: which distinct reagents are emblem-buyable (orbs,
    # Primordial Saronite) — the gear vendor table doesn't cover them
    rids = sorted({rid for rs in entries.values() for rid, _, _ in rs})
    print(f"{len(rids)} distinct reagents, pricing...", file=sys.stderr)
    prices = {}
    for n, rid in enumerate(rids, 1):
        try:
            p = emblem_cost(fetch(f"https://wotlkdb.com/?item={rid}", f"item{rid}"))
        except Exception as e:  # noqa: BLE001
            print(f"  reagent {rid}: fetch failed: {e}", file=sys.stderr)
            p = None
        if p:
            prices[rid] = p
        if n % 50 == 0:
            print(f"  {n}/{len(rids)}", file=sys.stderr)

    print("// Code generated by tools/gen_craftcosts.py from wotlkdb.com")
    print("// (3.3.5a database); DO NOT EDIT.")
    print()
    print("package db")
    print()
    print("var craftCosts = map[int][]Reagent{")
    for iid in sorted(entries):
        parts = ", ".join(
            f'{{{rid}, "{name.replace(chr(34), chr(92) + chr(34))}", {cnt}}}'
            for rid, name, cnt in entries[iid]
        )
        print(f"\t{iid}: {{{parts}}},")
    print("}")
    print()
    print("// reagentEmblems prices the emblem-buyable crafting reagents; the")
    print("// gear vendor table (emblems_gen.go) covers equippable items only.")
    print("var reagentEmblems = map[int]EmblemPrice{")
    for rid in sorted(prices):
        cur, cnt = prices[rid]
        print(f"\t{rid}: {{{EMBLEM_CURRENCIES[cur]}, {cnt}}},")
    print("}")
    if misses:
        print(f"no reagents found for: {misses}", file=sys.stderr)


if __name__ == "__main__":
    main()
