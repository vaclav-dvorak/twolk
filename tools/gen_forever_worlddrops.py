#!/usr/bin/env python3
"""Generate the Forever world-drop table -> internal/db/foreverworlddrops_gen.go:

  foreverWorldDrops   items the vendored wowsims data leaves sourceless
                      that QuestieDB shows dropping in the open world

wowsims records the sources a level-60 sim needs (quests, crafts,
vendors, dungeon/raid drops) and leaves ordinary world loot sourceless.
QuestieDB's Forever item table lists, per item, the NPCs and objects
that drop it. An item counts as a world drop when it drops from MORE
than MAX_SPECIFIC_NPCS NPCs or from any object (treasure chests). Items
with no drop data at all, a few specific mobs, or only containers stay
sourceless: "source unknown" is honest, a guess is not.

Data from QuestieDB (https://github.com/Questie/QuestieDB), used under
the GPLv3 terms the Questie team offers (see its LICENSE.md), pinned to
QUESTIE_COMMIT. The vendored wowsims data (internal/db/data) decides
which items are sourceless.

Usage:
    python3 tools/gen_forever_worlddrops.py | gofmt > internal/db/foreverworlddrops_gen.go
"""

import gzip
import json
import os
import re
import sys
import urllib.request

QUESTIE_COMMIT = "4377c981ac368d1593ec92788218e0a689a6a02b"
QUESTIE_ITEMS = ("https://raw.githubusercontent.com/Questie/QuestieDB/"
                 f"{QUESTIE_COMMIT}/data/Forever/foreverItemDB.lua")
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "internal", "db", "data")

MAX_SPECIFIC_NPCS = 3  # up to this many dropping NPCs is a named source, not world loot

# QuestieDB.itemKeys (1-based in Lua; 0-based here)
NPC_DROPS, OBJECT_DROPS = 1, 2


def lua_fields(body):
    """Split one item row's top-level fields (strings, nil, numbers,
    {tables}) without evaluating the Lua."""
    out, cur, depth, in_str, esc = [], "", 0, False, False
    for ch in body:
        if in_str:
            cur += ch
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == "'":
                in_str = False
            continue
        if ch == "'":
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            if depth == 0:
                break
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def ids(field):
    return [int(x) for x in re.findall(r"\d+", field)] if field and field != "nil" else []


def sourceless_items():
    items = {}
    for name in ("forever-db.json.gz", "forever-leftover-db.json.gz"):
        with gzip.open(os.path.join(DATA, name), "rt", encoding="utf-8") as f:
            for it in json.load(f)["items"]:
                items.setdefault(it["id"], it)
    return {i for i, it in items.items() if not it.get("sources")}


def main():
    req = urllib.request.Request(QUESTIE_ITEMS, headers={"User-Agent": "twolk-gen-forever-worlddrops/1.0"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        lua = resp.read().decode("utf-8", "replace")
    sourceless = sourceless_items()
    world = []
    for m in re.finditer(r"^\[(\d+)\] = \{(.*)$", lua, re.M):
        item = int(m.group(1))
        if item not in sourceless:
            continue
        f = lua_fields(m.group(2))
        npcs = ids(f[NPC_DROPS]) if len(f) > NPC_DROPS else []
        objects = ids(f[OBJECT_DROPS]) if len(f) > OBJECT_DROPS else []
        if len(npcs) > MAX_SPECIFIC_NPCS or objects:
            world.append(item)
    out = sys.stdout
    out.write("// Code generated by tools/gen_forever_worlddrops.py from QuestieDB\n")
    out.write(f"// ({QUESTIE_COMMIT[:12]}, GPLv3) and the vendored wowsims data; DO NOT EDIT.\n\n")
    out.write("package db\n\n")
    out.write(f"// foreverWorldDrops: {len(world)} items wowsims leaves sourceless.\n")
    out.write("var foreverWorldDrops = map[int]bool{\n")
    for i in sorted(world):
        out.write(f"\t{i}: true,\n")
    out.write("}\n")
    print(f"{len(world)} world drops of {len(sourceless)} sourceless items", file=sys.stderr)


if __name__ == "__main__":
    main()
