#!/usr/bin/env python3
"""Generate internal/score/simweights_gen.go — the default stat weights
of every WoWSims spec sim at the pinned commit, adopted VERBATIM in
each sim's own normalization (physical DPS sims anchor AP/RAP = 1,
caster/healer sims SpellPower = 1 with HPS-derived ratios, tank sims
mixed survival/threat scales). No re-normalization to AP-equivalents:
weights are relative, only ratios matter, and an AP anchor is
meaningless for healers and tanks anyway.

Hybrid specs (DK, ret, enhancement) weight BOTH sides of a duplicated
rating on purpose: items carry hit as MeleeHit AND SpellHit, and the
rating's full value is the sum of what each side contributes.

Usage:
    python3 tools/gen_simweights.py > internal/score/simweights_gen.go

Env:
    GEN_SIMWEIGHTS_CACHE  directory with <spec>.ts files to skip fetching
"""

import os
import re
import sys
import time
import urllib.request

PINNED = "02e0d9fba5acb5c0a3d9248cb82285641540a1a9"

SPECS = [
    "balance_druid", "deathknight", "elemental_shaman", "enhancement_shaman",
    "feral_druid", "feral_tank_druid", "healing_priest", "holy_paladin",
    "hunter", "mage", "protection_paladin", "protection_warrior",
    "restoration_druid", "restoration_shaman", "retribution_paladin",
    "rogue", "shadow_priest", "smite_priest", "tank_deathknight",
    "warlock", "warrior",
]

# WoWSims TS Stat.Stat<X> names -> our db.Stat constant names (1:1)
STAT_OK = {
    "Strength", "Agility", "Stamina", "Intellect", "Spirit", "SpellPower",
    "MP5", "SpellHit", "SpellCrit", "SpellHaste", "SpellPenetration",
    "AttackPower", "MeleeHit", "MeleeCrit", "MeleeHaste", "ArmorPenetration",
    "Expertise", "Mana", "Armor", "RangedAttackPower", "Defense", "Block",
    "BlockValue", "Dodge", "Parry", "Resilience", "Health", "BonusArmor",
}


def fetch(spec):
    cache = os.environ.get("GEN_SIMWEIGHTS_CACHE")
    fn = cache and f"{cache}/{spec}.ts"
    if fn and os.path.exists(fn):
        with open(fn) as f:
            return f.read()
    url = f"https://raw.githubusercontent.com/wowsims/wotlk/{PINNED}/ui/{spec}/sim.ts"
    req = urllib.request.Request(url, headers={"User-Agent": "twolk-gen-simweights/1.0"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        src = resp.read().decode()
    time.sleep(1)
    if fn:
        with open(fn, "w") as f:
            f.write(src)
    return src


def main():
    print("// Code generated by tools/gen_simweights.py from WoWSims")
    print(f"// ui/<spec>/sim.ts at {PINNED[:12]}; DO NOT EDIT.")
    print()
    print("package score")
    print()
    print('import "github.com/vaclav-dvorak/twolk/internal/db"')
    print()
    print("// simWeight is one WoWSims spec sim's default stat weights,")
    print("// verbatim in the sim's own normalization, plus its weapon-DPS")
    print("// pseudo-stat weights (EP per point of weapon DPS).")
    print("type simWeight struct {")
    print("\tStats          db.Stats")
    print("\tMH, OH, Ranged float64")
    print("}")
    print()
    print("var simWeights = map[string]simWeight{")
    for spec in SPECS:
        src = fetch(spec)
        m = re.search(r"epWeights:\s*Stats\.fromMap\(\{(.*?)\}(?:,\s*\{(.*?)\})?\s*\)", src, re.S)
        if not m:
            print(f"WARNING: {spec}: no epWeights found", file=sys.stderr)
            continue
        stats = re.findall(r"\[Stat\.Stat(\w+)\]:\s*([\d.]+)", m.group(1))
        pseudo = dict(re.findall(r"\[PseudoStat\.PseudoStat(\w+)\]:\s*([\d.]+)", m.group(2) or ""))
        parts = []
        for name, v in stats:
            if name not in STAT_OK:
                print(f"WARNING: {spec}: unmapped stat {name}", file=sys.stderr)
                continue
            if float(v) == 0:
                continue
            parts.append(f"db.{name}: {v}")
        fields = [f"Stats: db.Stats{{{', '.join(parts)}}}"]
        for k, f in (("MainHandDps", "MH"), ("OffHandDps", "OH"), ("RangedDps", "Ranged")):
            if k in pseudo and float(pseudo[k]) != 0:
                fields.append(f"{f}: {pseudo[k]}")
        print(f'\t"{spec}": {{{", ".join(fields)}}},')
    print("}")


if __name__ == "__main__":
    main()
