#!/usr/bin/env python3
"""Generate internal/tui/classicons_gen.go — WoW class icons as pixel data.

Downloads the official class icons (one 56x56 jpg per class from wowhead's
static CDN), downsizes them with macOS `sips` to 16x16, and emits RGB pixel
rows. The TUI renders them as terminal pixel-art using half-block glyphs
(▀ with foreground = upper pixel, background = lower pixel).

Usage:
    python3 tools/gen_classicons.py > internal/tui/classicons_gen.go
"""

import os
import struct
import subprocess
import sys
import tempfile
import time
import urllib.request

SIZE = 16
CLASSES = {  # Go class name -> zamimg icon slug
    "Warrior": "warrior", "Paladin": "paladin", "Hunter": "hunter",
    "Rogue": "rogue", "Priest": "priest", "DeathKnight": "deathknight",
    "Shaman": "shaman", "Mage": "mage", "Warlock": "warlock", "Druid": "druid",
}


def fetch_icon(slug, workdir):
    url = f"https://wow.zamimg.com/images/wow/icons/large/classicon_{slug}.jpg"
    jpg = os.path.join(workdir, f"{slug}.jpg")
    req = urllib.request.Request(url, headers={"User-Agent": "twolk-gen-classicons/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r, open(jpg, "wb") as f:
        f.write(r.read())
    time.sleep(0.5)
    bmp = os.path.join(workdir, f"{slug}.bmp")
    subprocess.run(
        ["sips", "-z", str(SIZE), str(SIZE), "-s", "format", "bmp", jpg, "--out", bmp],
        check=True, capture_output=True,
    )
    return bmp


def read_bmp(path):
    """Minimal uncompressed 24/32-bit BMP reader → rows of 0xRRGGBB, top-down."""
    data = open(path, "rb").read()
    off = struct.unpack_from("<I", data, 10)[0]
    w = struct.unpack_from("<i", data, 18)[0]
    h = struct.unpack_from("<i", data, 22)[0]
    bpp = struct.unpack_from("<H", data, 28)[0]
    assert bpp in (24, 32), f"unsupported bpp {bpp}"
    step = bpp // 8
    stride = (w * step + 3) & ~3
    flip = h > 0
    h = abs(h)
    rows = []
    for y in range(h):
        src = (h - 1 - y) if flip else y
        row = []
        for x in range(w):
            i = off + src * stride + x * step
            b, g, r = data[i], data[i + 1], data[i + 2]
            row.append((r << 16) | (g << 8) | b)
        rows.append(row)
    return rows


def main():
    print("// Code generated by tools/gen_classicons.py from wowhead's")
    print("// class icon images (wow.zamimg.com); DO NOT EDIT.")
    print()
    print("package tui")
    print()
    print(f"// classIconPixels holds {SIZE}x{SIZE} RGB pixels per class,")
    print("// rendered as half-block terminal pixel art.")
    print("var classIconPixels = map[string][][]uint32{")
    with tempfile.TemporaryDirectory() as workdir:
        for name, slug in CLASSES.items():
            rows = read_bmp(fetch_icon(slug, workdir))
            print(f'\t"{name}": {{')
            for row in rows:
                print("\t\t{" + ", ".join(f"0x{p:06x}" for p in row) + "},")
            print("\t},")
            print(f"  {name} ok", file=sys.stderr)
    print("}")


if __name__ == "__main__":
    main()
