#!/usr/bin/env python3
"""Generate the Forever craft tables -> internal/db/forevercrafts_gen.go:

  foreverCraftSkills  craft spell -> the profession skill that learns it
  foreverBoPCrafts    crafted items that bind on pickup (only their
                      crafter can wear them — never on the AH)

The learn level is client data only for recipes taught by a pattern
item ("Pattern: Skulker's Leather Belt" requires Leatherworking 150):
ItemSparse.RequiredSkillRank of the item whose learn effect
(ItemEffect trigger 6, joined through ItemXItemEffect) is the craft.
Trainer recipes keep theirs on the server; they are ESTIMATED from
SkillLineAbility: the recipe's own MinSkillLineRank when it carries one,
else its yellow threshold (TrivialSkillLineRankLow) minus 5. Across the
pattern recipes yellow sits 5-25 above the learn level, >= 5 for 98% of
them, so the estimate rarely claims a recipe early and at worst hides
one ~20 points too long.

Bulk upstreams only (no scraping): wago.tools client-table CSVs at the
Forever build (their robots.txt allows /db2/*/csv), and the crafted
sources of the vendored wowsims database (internal/db/data).

Usage:
    python3 tools/gen_forever_crafts.py [build] | gofmt > internal/db/forevercrafts_gen.go

Env:
    WAGO_CSV   directory caching wago.tools CSVs (per-build subdirs)
"""

import csv
import gzip
import io
import json
import os
import sys
import urllib.request

BUILD = "1.60.1.71091"  # the build of the vendored wowsims data
WAGO = "https://wago.tools/db2/{}/csv?build={}"
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "internal", "db", "data")

ITEM_SPELLTRIGGER_LEARN = 6
BIND_ON_PICKUP = "1"
TRAINER_YELLOW_GAP = 5


def load_wago(table, build):
    cache = os.environ.get("WAGO_CSV")
    fp = cache and os.path.join(cache, build, table + ".csv")
    if fp and os.path.exists(fp):
        with open(fp, encoding="utf-8") as f:
            return list(csv.DictReader(f))
    req = urllib.request.Request(WAGO.format(table, build), headers={"User-Agent": "twolk-gen-forever-crafts/1.0"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        text = resp.read().decode("utf-8", "replace")
    if fp:
        os.makedirs(os.path.dirname(fp), exist_ok=True)
        with open(fp, "w", encoding="utf-8") as f:
            f.write(text)
    return list(csv.DictReader(io.StringIO(text)))


def crafted_sources():
    """craft spell -> crafted item id, from the vendored wowsims data."""
    crafts = {}
    for name in ("forever-db.json.gz", "forever-leftover-db.json.gz"):
        with gzip.open(os.path.join(DATA, name), "rt", encoding="utf-8") as f:
            for it in json.load(f)["items"]:
                for s in it.get("sources", []):
                    c = s.get("crafted")
                    if c and c.get("spellId"):
                        crafts.setdefault(c["spellId"], it["id"])
    return crafts


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else BUILD
    crafts = crafted_sources()
    sparse = {int(r["ID"]): r for r in load_wago("ItemSparse", build)}
    effects = {int(r["ID"]): r for r in load_wago("ItemEffect", build)}

    # exact: the lowest pattern that teaches the craft
    learn = {}
    for x in load_wago("ItemXItemEffect", build):
        e = effects.get(int(x["ItemEffectID"]))
        it = sparse.get(int(x["ItemID"]))
        if not e or not it or e["TriggerType"] != str(ITEM_SPELLTRIGGER_LEARN) or it["RequiredSkill"] == "0":
            continue
        sp = int(e["SpellID"])
        if sp in crafts:
            learn[sp] = min(learn.get(sp, 1 << 30), int(it["RequiredSkillRank"]))

    estimated = {}
    for r in load_wago("SkillLineAbility", build):
        sp = int(r["Spell"])
        if sp not in crafts or sp in learn:
            continue
        rank = int(r["MinSkillLineRank"])
        if rank <= 1:
            rank = max(int(r["TrivialSkillLineRankLow"]) - TRAINER_YELLOW_GAP, 1)
        estimated[sp] = rank

    bop = sorted(i for i in set(crafts.values()) if i in sparse and sparse[i]["Bonding"] == BIND_ON_PICKUP)

    out = sys.stdout
    out.write(f"// Code generated by tools/gen_forever_crafts.py from wago.tools client tables\n")
    out.write(f"// (build {build}) and the vendored wowsims crafted sources; DO NOT EDIT.\n\n")
    out.write("package db\n\n")
    out.write(f"// foreverCraftSkills: {len(learn)} exact (pattern items), {len(estimated)} estimated (trainer).\n")
    out.write("var foreverCraftSkills = map[int]CraftSkill{\n")
    for sp in sorted(set(learn) | set(estimated)):
        if sp in learn:
            out.write(f"\t{sp}: {{Learn: {learn[sp]}}},\n")
        else:
            out.write(f"\t{sp}: {{Learn: {estimated[sp]}, Estimated: true}},\n")
    out.write("}\n\n")
    out.write("var foreverBoPCrafts = map[int]bool{\n")
    for i in bop:
        out.write(f"\t{i}: true,\n")
    out.write("}\n")
    print(f"{len(learn)} exact, {len(estimated)} estimated, "
          f"{len(crafts) - len(learn) - len(estimated)} unknown, {len(bop)} BoP crafts", file=sys.stderr)


if __name__ == "__main__":
    main()
