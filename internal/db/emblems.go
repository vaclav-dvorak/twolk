package db

import "fmt"

// Emblem is a PvE gear currency: the five 3.3.5 badges, plus the
// Cataclysm point currencies (appended — positions are stable).
type Emblem int

const (
	EmblemNone Emblem = iota
	EmblemHeroism
	EmblemValor
	EmblemConquest
	EmblemTriumph
	EmblemFrost
	EmblemJustice     // Cataclysm Justice Points
	EmblemValorPoints // Cataclysm Valor Points
	EmblemFissure     // Fissure Stone Fragment (Classic Protocol Inferno)
	EmblemObsidian    // Obsidian Fragment (Classic Protocol Twilight)
)

var emblemNames = [...]string{"", "Emblem of Heroism", "Emblem of Valor",
	"Emblem of Conquest", "Emblem of Triumph", "Emblem of Frost",
	"Justice Points", "Valor Points",
	"Fissure Stone Fragment", "Obsidian Fragment"}

func (e Emblem) String() string {
	if e > 0 && int(e) < len(emblemNames) {
		return emblemNames[e]
	}
	return fmt.Sprintf("Emblem(%d)", int(e))
}

// EmblemPrice is what an item costs at the badge vendors. The table
// behind it (emblems_gen.go) is generated by tools/gen_vendorcosts.py
// from AzerothCore npc_vendor + wotlkdb.com NPC pages — original 3.3.5
// data, independent of the WoWSims item database, complete (the older
// per-currency scrape lost ~190 items to a 300-row listview cap).
type EmblemPrice struct {
	Emblem Emblem
	Count  int
}

// EmblemPriceFor returns the currency cost of an item, if it is
// point-buyable: 3.3.5 gear from the badge vendor table, crafting
// reagents (orbs, Primordial Saronite) from the reagent table, cata
// gear from the generated justice/valor table (catacosts_gen.go).
// The id spaces coexist safely: each database only looks up its own
// items.
func EmblemPriceFor(itemID int) (EmblemPrice, bool) {
	if p, ok := emblemPrices[itemID]; ok {
		return p, ok
	}
	if p, ok := cataVendorPrices[itemID]; ok {
		return p, ok
	}
	p, ok := reagentEmblems[itemID]
	return p, ok
}

// ProtocolPrice is an acquisition route through the heroic-plus
// dungeon economy (Cataclysm Classic's Elemental Rune protocols): gear
// bought with fragments farmed in 5-man protocol runs — raid loot
// WITHOUT a raid group. Phase gates the route itself: the vendor and
// its currency do not exist on the server before that phase, no matter
// how early the ITEM's own content phase is (a T11 raid drop is
// phase-1 loot but only fragment-buyable once Protocol Inferno ships
// with Firelands).
type ProtocolPrice struct {
	Emblem Emblem
	Count  int    // 0: stocked by the vendor, exact cost not in our data
	Phase  int    // planner phase the protocol (and its vendor) opens
	Label  string // "Protocol Inferno" / "Protocol Twilight"
	Drops  bool   // also drops from protocol final bosses (DS LFR gear)
}

// PriceFor is the phase-aware price lookup: the raw table value run
// through the version's RotatePrice rule (see RuleSet.RotatePrice —
// Cataclysm Classic rotates a tier's currency as later phases open).
// Non-gear ids (craft reagents) have no ilvl and never rotate.
func (d *Database) PriceFor(itemID, phase int) (EmblemPrice, bool) {
	p, ok := EmblemPriceFor(itemID)
	if !ok {
		return p, false
	}
	if it := d.Items[itemID]; it != nil && d.Rules.RotatePrice != nil {
		p = d.Rules.RotatePrice(p, it.ILvl, phase)
	}
	return p, true
}
